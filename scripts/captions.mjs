import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { ROOT } from './paths.mjs';
import { parseLrc } from '../dist/film/timeline.mjs';

const letters=text=>text.toLowerCase().replace(/[^a-z]/g,'');
const correct=text=>text.replace('a set of point','a set of points').replace('all the simulations','all the stimulations').replace('give u my','give you my').replace('Trios, ne','Trois, ne').replace('Oh, my switch role','Oh, switch my role');

export async function bilingualCues(source){
  const directory=path.join(ROOT,'references','translations');
  const [reference,timing]=await Promise.all([
    readFile(path.join(directory,'user-provided.txt'),'utf8'),
    readFile(path.join(directory,'phrase-timing.lrc'),'utf8'),
  ]);
  const lines=reference.trim().split(/\r?\n/).slice(2);
  const fine=parseLrc(timing),coarse=parseLrc(source);
  if(fine.length!==Math.ceil(lines.length/2))throw new Error('Reference lyric line count changed');
  // Match whole-song character positions, so repeated phrases remain distinct.
  // Existing phrase onsets stay fixed. Within each span, the reference project's
  // fine timing supplies the relative spacing of the user's standalone lines.
  let offset=0;
  const coarseAt=new Map();
  for(const cue of coarse)if(cue.text){coarseAt.set(offset,cue.time);offset+=letters(correct(cue.text)).length;}
  const original=coarse.map(c=>letters(correct(c.text))).join('');
  const refined=fine.filter(c=>c.text!=='world.execute(me);').map(c=>letters(c.text)).join('');
  if(original!==refined)throw new Error('LRC and line reference do not describe the same word sequence');
  offset=0;
  const anchors=[];
  for(const cue of fine){
    if(cue.text==='world.execute(me);')continue;
    if(coarseAt.has(offset))anchors.push({fine:cue.time,original:coarseAt.get(offset)});
    offset+=letters(cue.text).length;
  }
  function aligned(time){
    const a=anchors.findLast(a=>a.fine<=time)??anchors[0];
    const b=anchors.find(b=>b.fine>time);
    return Math.round((b?a.original+(time-a.fine)/(b.fine-a.fine)*(b.original-a.original):a.original+time-a.fine)*1000)/1000;
  }
  const cues=fine.map((cue,index)=>{
    const text=lines[index*2],zh=lines[index*2+1]??(index===fine.length-1?'执行死刑':undefined);
    if(cue.text!==text||!zh)throw new Error(`Reference mismatch on lyric line ${index+1}`);
    if(text==='world.execute(me);')return {time:16.04,text:'',zh:'',keyword:false};
    return {time:aligned(cue.time),text,zh,keyword:/^[A-Z][A-Z -]+$/.test(text)};
  });
  cues.push(...coarse.filter(c=>!c.text&&c.time!==16.04).map(c=>({...c,zh:'',keyword:false})));
  return cues.sort((a,b)=>a.time-b.time);
}

export async function writeCues(media,cues){
  const {writeFile}=await import('node:fs/promises');
  await writeFile(path.join(media,'cues.json'),JSON.stringify(cues));
  await writeFile(path.join(media,'cues.mjs'),`// Generated by npm run prepare:captions. Times exclude LYRIC_DELAY.\nexport const CUES = ${JSON.stringify(cues,null,2)};\n`);
}
